/** A bound translate function that also does `{n}`-style interpolation. */
export type Translate = (key: LocaleKey, vars?: Record<string, string | number>) => string

/**
 * Wrap the raw locale binding so a missing key degrades to `[key]` instead of
 * rendering `undefined`, and support `{var}` interpolation in one place.
 */
export function makeSafeTranslate(bound: (key: string) => string): Translate {
  return (key, vars) => {
    let out = bound(key)
    if (out === undefined || out === null || out === '' || out === key) out = zh[key] ?? `[${key}]`
    if (vars !== undefined) {
      for (const [name, value] of Object.entries(vars)) {
        out = out.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value))
      }
    }
    return out
  }
}
